# ============================================================
# 업앤다운 숫자 맞추기 게임 — 예시 답안 C (보통)
# 예상 점수: 44점 / 50점
#   정답 생성 및 비교 로직 9 ← randint(1, 99): 100이 정답으로 나오지 않음
#   반복문 제어 및 종료 10
#   시도 횟수 카운트 9      ← 횟수는 세지만 결과로 출력하지 않음
#   예외 처리 및 안정성 8   ← 100보다 큰 수만 막고 0·음수는 그대로 받음
#   코드 품질 8             ← 변수명이 a, b, c / 재시작 기능 없음
# ============================================================
import random

a = random.randint(1, 99)
c = 0

while True:
    b = int(input("숫자 입력(1~100): "))
    if b > 100:
        print("100 이하로 입력하세요.")
        continue
    c += 1
    if b < a:
        print("UP")
    elif b > a:
        print("DOWN")
    else:
        print("정답입니다!")
        break
