def rubric_text():
    """채점 프롬프트에 넣을 채점기준 전문."""
    parts = []
    for key, name, levels in CRITERIA:
        parts.append(f"[{key}] {name} (10점 만점)")
        for score, desc in levels:
            parts.append(f"  - {score}점: {desc}")
    parts.append("")
    parts.append("[성취수준]")
    for level, desc in ACHIEVEMENT_LEVELS.items():
        parts.append(f"  - {level}: {desc}")
    return "\n".join(parts)
