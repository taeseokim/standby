# BMI 5단계 (대한비만학회 성인 기준을 5단계로 정리)
# (상한값, 단계명) — BMI가 상한값 '미만'이면 해당 단계. 마지막 단계는 상한 없음.
BMI_STAGES = [
    (18.5, "저체중"),
    (23.0, "정상"),
    (25.0, "과체중"),
    (30.0, "비만"),
    (None, "고도비만"),
]


def bmi_stage(bmi):
    """BMI 값에 해당하는 단계명을 돌려준다."""
    for upper, name in BMI_STAGES:
        if upper is None or bmi < upper:
            return name
    return BMI_STAGES[-1][1]


def bmi_stage_table():
    """학생 안내·채점 프롬프트에 쓰는 단계 표 문자열."""
    lines = []
    lower = None
    for upper, name in BMI_STAGES:
        if lower is None:
            lines.append(f"- {name}: BMI {upper} 미만")
        elif upper is None:
            lines.append(f"- {name}: BMI {lower} 이상")
        else:
            lines.append(f"- {name}: BMI {lower} 이상 {upper} 미만")
        lower = upper
    return "\n".join(lines)


